"""
Extended version of the original 2023-2026 download script: covers May-2018
to June-2026 (instead of just 2023-2026), and computes statistics for TWO
regions in the same download pass:
  1. "embalse" (reservoir): the full reservoir polygon (same as the
     original script) -- reservoir-wide median/percentiles/bloom extent.
  2. "cortina" (near-dam): a core area near the dam (mapas/cerca_cortina_nucleo.gpkg),
     built by eroding the reservoir polygon 350m inward (more than 1 OLCI
     pixel of ~300m) and intersecting with mapas/cerca-cortina.gpkg, to
     exclude mixed land/water pixels near the shoreline. This core was
     generated by an auxiliary script (see project notes) and is already
     saved in mapas/cerca_cortina_nucleo.gpkg -- about 24 OLCI pixels fit
     inside it.

Why a new script instead of extending the original one: the raw netCDF
files for each date are deleted after computing statistics (to avoid
filling up disk), so adding a second region requires re-downloading the
ENTIRE period, including the 2023-2026 part already processed before --
this same re-download is used to extend the period at the same time, in a
single pass, instead of two separate downloads.

Period May-2018 to June-2026: May-2018 (not April-2016) was chosen as the
start because Sentinel-3B became operational in mid-May-2018; before that
only S3A was available, at half the combined temporal density (~2-day
revisit instead of ~1). The full catalogue since 2016 IS available if the
period needs to be extended further in the future, but it would mix two
very different sampling densities without explicit separate treatment.

Input:
  - tablas/catalogo_s3_wfr_2018_2026.csv
  - mapas/ContornoSolis_latlong.gpkg
  - mapas/cerca_cortina_nucleo.gpkg
Output:
  - tablas/Sentinel3_serie_temporal_extendida.csv (one row per satellite-date,
    with embalse_* and cortina_* columns)
"""

import os, csv, time, shutil, configparser
import numpy as np
import boto3
from botocore.config import Config
import netCDF4
from osgeo import ogr
import shapely.wkt
import shapely.vectorized

BASE = "/home/jf/pCloudDrive/trabajos/PresaSolis"
CATALOGO = os.path.join(BASE, "tablas/catalogo_s3_wfr_2018_2026.csv")
POLIGONO_EMBALSE = os.path.join(BASE, "mapas/ContornoSolis_latlong.gpkg")
POLIGONO_CORTINA = os.path.join(BASE, "mapas/cerca_cortina_nucleo.gpkg")
OUT_CSV = os.path.join(BASE, "tablas/Sentinel3_serie_temporal_extendida.csv")
TMP_DIR = "/tmp/s3wfr_descarga_temporal_ext"

# Only these 5 files of the full product are downloaded (~32% of the total size,
# Supplementary Material S5); the rest of the product is not needed for this analysis.
ARCHIVOS_NECESARIOS = ["chl_nn.nc", "chl_oc4me.nc", "tsm_nn.nc", "wqsf.nc", "geo_coordinates.nc"]
UMBRAL_FLORACION_UGL = 50.0
AREA_PIXEL_KM2 = 0.3 * 0.3  # OLCI nominal resolution, 300 x 300 m

REGIONES = ["embalse", "cortina"]

CAMPOS_SALIDA = ["satelite", "fecha", "n_frames", "nombres_frames"]
for reg in REGIONES:
    CAMPOS_SALIDA += [
        f"{reg}_n_pixeles_poligono", f"{reg}_n_pixeles_validos", f"{reg}_frac_validos",
        f"{reg}_chl_nn_mediana", f"{reg}_chl_nn_p10", f"{reg}_chl_nn_p25", f"{reg}_chl_nn_p75", f"{reg}_chl_nn_p90",
        f"{reg}_chl_oc4me_mediana", f"{reg}_n_validos_chl_oc4me",
        f"{reg}_tsm_nn_mediana", f"{reg}_n_validos_tsm_nn",
        f"{reg}_n_pixeles_floracion", f"{reg}_area_floracion_km2", f"{reg}_frac_floracion",
    ]


def carga_poligono_wkt(gpkg_path):
    ds = ogr.Open(gpkg_path)
    layer = ds.GetLayer(0)
    feat = layer.GetNextFeature()
    geom = feat.GetGeometryRef()
    wkt = geom.ExportToWkt()
    ds = None
    return shapely.wkt.loads(wkt)


def cliente_s3():
    cfg = configparser.ConfigParser()
    cfg.read(os.path.expanduser("~/.aws/credentials"))
    ak = cfg["cdse"]["aws_access_key_id"].strip()
    sk = cfg["cdse"]["aws_secret_access_key"].strip()
    return boto3.client(
        "s3", endpoint_url="https://eodata.dataspace.copernicus.eu",
        aws_access_key_id=ak, aws_secret_access_key=sk, region_name="default",
        config=Config(retries={"max_attempts": 5, "mode": "adaptive"}),
    )


def descarga_frame(s3, s3path, destino):
    """Resilient per file: if a single file is missing (e.g. chl_oc4me.nc was
    renamed to chlor_a.nc when ESA switched from baseline 003 to 004 in
    feb-2026, with a different algorithm, Supplementary Material S5), only
    THAT file is skipped instead of discarding the whole satellite-date;
    CHL_NN/TSM_NN/WQSF/geolocation were unaffected by the transition. See the
    original download script for the full note."""
    prefix = s3path.lstrip("/")
    if prefix.startswith("eodata/"):
        prefix = prefix[len("eodata/"):]
    os.makedirs(destino, exist_ok=True)
    faltantes = []
    for nombre in ARCHIVOS_NECESARIOS:
        key = f"{prefix}/{nombre}"
        local = os.path.join(destino, nombre)
        try:
            s3.download_file("eodata", key, local)
        except Exception:
            faltantes.append(nombre)
    return faltantes


def lee_flags_wqsf(carpeta):
    nc = netCDF4.Dataset(os.path.join(carpeta, "wqsf.nc"))
    var = nc.variables["WQSF"]
    meanings = var.flag_meanings.split(" ")
    masks = var.flag_masks
    nc.close()
    return dict(zip(meanings, [int(m) for m in masks]))


def masked_a_nan(var_slice):
    arr = np.ma.masked_invalid(var_slice)
    return np.ma.filled(arr.astype(np.float64), np.nan)


def procesa_frame(carpeta, poligono_embalse, poligono_cortina):
    """Returns a dict with, for each region, (inside, good) plus the
    variables read ONCE (shared between regions), or None if the
    reservoir does not fall within this frame."""
    ncgeo = netCDF4.Dataset(os.path.join(carpeta, "geo_coordinates.nc"))
    lat = masked_a_nan(ncgeo.variables["latitude"][:])
    lon = masked_a_nan(ncgeo.variables["longitude"][:])
    ncgeo.close()

    # Cheap bounding box BEFORE the (expensive) vectorized contains(): discards
    # upfront the large majority of OLCI swath pixels that are not even near
    # the reservoir, without having to evaluate the exact polygon for each one.
    caja = (lon > -100.75) & (lon < -100.40) & (lat > 19.95) & (lat < 20.20)
    if not np.any(caja):
        return None

    idx_caja = np.where(caja)

    dentro_embalse = np.zeros_like(caja)
    dentro_embalse[idx_caja] = shapely.vectorized.contains(poligono_embalse, lon[idx_caja], lat[idx_caja])
    if not np.any(dentro_embalse):
        return None

    dentro_cortina = np.zeros_like(caja)
    dentro_cortina[idx_caja] = shapely.vectorized.contains(poligono_cortina, lon[idx_caja], lat[idx_caja])

    # The WQSF bits do NOT follow the "standard" order of generic OLCI
    # documentation (see Supplementary Material S2 of the manuscript); that is
    # why flag_masks/flag_meanings are read from each file instead of assumed fixed.
    flags_map = lee_flags_wqsf(carpeta)
    nc = netCDF4.Dataset(os.path.join(carpeta, "wqsf.nc"))
    wqsf = masked_a_nan(nc.variables["WQSF"][:])
    nc.close()
    # This product's flag_masks are signed 32-bit integers; converting to
    # int64 a value with bit 31 set would be interpreted as negative. The
    # modulo normalizes to the low 31 bits so that bitwise AND comparisons
    # with flag_masks (also read as signed integers) give the correct result.
    wqsf_i = np.nan_to_num(wqsf, nan=0.0).astype(np.int64) % (2**31)

    mascara_mala = 0
    for nombre in ["INVALID", "CLOUD", "SNOW_ICE", "CLOUD_AMBIGUOUS", "CLOUD_MARGIN"]:
        if nombre in flags_map:
            mascara_mala |= flags_map[nombre]
    mascara_agua = 0
    for nombre in ["WATER", "INLAND_WATER"]:
        if nombre in flags_map:
            mascara_agua |= flags_map[nombre]
    # LAND is not used in the exclusion mask: it co-occurs with INLAND_WATER
    # for this reservoir (a known classifier artefact for inland water
    # bodies), so excluding by LAND would also discard valid water pixels.

    es_agua = (wqsf_i & mascara_agua) != 0
    bandera_mala = (wqsf_i & mascara_mala) != 0
    buenos_base = es_agua & (~bandera_mala)

    variables = {}
    for archivo, varname, clave in [
        ("chl_nn.nc", "CHL_NN", "chl_nn"),
        ("chl_oc4me.nc", "CHL_OC4ME", "chl_oc4me"),
        ("tsm_nn.nc", "TSM_NN", "tsm_nn"),
    ]:
        ruta = os.path.join(carpeta, archivo)
        if not os.path.exists(ruta):
            variables[clave] = None
            continue
        nc = netCDF4.Dataset(ruta)
        variables[clave] = masked_a_nan(nc.variables[varname][:])
        nc.close()

    return {
        "embalse": (dentro_embalse, dentro_embalse & buenos_base),
        "cortina": (dentro_cortina, dentro_cortina & buenos_base),
        "variables": variables,
    }


def combina_y_calcula_region(resultados_frames, region):
    # Several "frames" (swath segments) can fall on the same satellite-date
    # when the reservoir sits right at the border between consecutive WFR
    # granules; they are ALL pooled before computing statistics so that no
    # part of the polygon is lost.
    n_poligono = sum(int(np.sum(r[region][0])) for r in resultados_frames)
    pools = {"chl_nn": [], "chl_oc4me": [], "tsm_nn": []}
    n_validos = 0
    for r in resultados_frames:
        buenos = r[region][1]
        n_validos += int(np.sum(buenos))
        for clave in pools:
            var = r["variables"][clave]
            if var is None:
                continue
            vals = var[buenos]
            vals = vals[np.isfinite(vals)]
            # OLCI's chlorophyll/TSM products come on a log10 scale (see
            # Methods 3.2 of the manuscript); back-transformed here, before
            # pooling and averaging, so the averaging is not done in log scale.
            pools[clave].append(10 ** vals)

    for clave in pools:
        pools[clave] = np.concatenate(pools[clave]) if pools[clave] else np.array([])

    fila = {
        f"{region}_n_pixeles_poligono": n_poligono,
        f"{region}_n_pixeles_validos": n_validos,
        f"{region}_frac_validos": n_validos / n_poligono if n_poligono else np.nan,
    }

    def pct(v, q):
        return float(np.percentile(v, q)) if len(v) else np.nan

    chl_nn = pools["chl_nn"]
    fila[f"{region}_chl_nn_mediana"] = pct(chl_nn, 50)
    fila[f"{region}_chl_nn_p10"] = pct(chl_nn, 10)
    fila[f"{region}_chl_nn_p25"] = pct(chl_nn, 25)
    fila[f"{region}_chl_nn_p75"] = pct(chl_nn, 75)
    fila[f"{region}_chl_nn_p90"] = pct(chl_nn, 90)

    fila[f"{region}_chl_oc4me_mediana"] = pct(pools["chl_oc4me"], 50)
    fila[f"{region}_n_validos_chl_oc4me"] = len(pools["chl_oc4me"])
    fila[f"{region}_tsm_nn_mediana"] = pct(pools["tsm_nn"], 50)
    fila[f"{region}_n_validos_tsm_nn"] = len(pools["tsm_nn"])

    n_floracion = int(np.sum(chl_nn > UMBRAL_FLORACION_UGL)) if len(chl_nn) else 0
    fila[f"{region}_n_pixeles_floracion"] = n_floracion
    fila[f"{region}_area_floracion_km2"] = n_floracion * AREA_PIXEL_KM2
    fila[f"{region}_frac_floracion"] = n_floracion / len(chl_nn) if len(chl_nn) else np.nan

    return fila


def main():
    poligono_embalse = carga_poligono_wkt(POLIGONO_EMBALSE)
    poligono_cortina = carga_poligono_wkt(POLIGONO_CORTINA)
    s3 = cliente_s3()

    with open(CATALOGO) as f:
        escenas = list(csv.DictReader(f))

    grupos = {}
    for e in escenas:
        satelite = e["Name"][0:3]
        fecha = e["ContentDate_Start"][0:10]
        grupos.setdefault((satelite, fecha), []).append(e)

    claves_ordenadas = sorted(grupos.keys(), key=lambda k: (k[1], k[0]))

    # Resumable: if OUT_CSV already exists (from a previously interrupted run),
    # dates that already have a row are not downloaded/processed again.
    ya_procesadas = set()
    escribir_encabezado = not os.path.exists(OUT_CSV)
    if os.path.exists(OUT_CSV):
        with open(OUT_CSV) as f:
            for r in csv.DictReader(f):
                ya_procesadas.add((r["satelite"], r["fecha"]))

    pendientes = [k for k in claves_ordenadas if k not in ya_procesadas]
    print(f"Total satellite-dates in catalogue: {len(claves_ordenadas)}. "
          f"Already processed: {len(ya_procesadas)}. Pending: {len(pendientes)}")

    with open(OUT_CSV, "a", newline="") as fout:
        writer = csv.DictWriter(fout, fieldnames=CAMPOS_SALIDA)
        if escribir_encabezado:
            writer.writeheader()
            fout.flush()

        t0 = time.time()
        for i, (satelite, fecha) in enumerate(pendientes):
            frames_catalogo = grupos[(satelite, fecha)]
            resultados_frames = []
            for esc in frames_catalogo:
                destino = os.path.join(TMP_DIR, esc["Name"])
                try:
                    faltantes = descarga_frame(s3, esc["S3Path"], destino)
                    if faltantes:
                        print(f"[{i+1}/{len(pendientes)}] {esc['Name']}: files unavailable: {faltantes}")
                    r = procesa_frame(destino, poligono_embalse, poligono_cortina)
                    if r is not None:
                        resultados_frames.append(r)
                except Exception as e:
                    print(f"[{i+1}/{len(pendientes)}] ERROR on {esc['Name']}: {e}")
                finally:
                    # The raw netCDF files are deleted immediately after extracting
                    # statistics for this frame, to avoid accumulating ~427 GB on disk.
                    shutil.rmtree(destino, ignore_errors=True)

            fila = {
                "satelite": satelite, "fecha": fecha,
                "n_frames": len(resultados_frames),
                "nombres_frames": ";".join(e["Name"] for e in frames_catalogo),
            }
            if resultados_frames:
                for region in REGIONES:
                    fila.update(combina_y_calcula_region(resultados_frames, region))
            else:
                for k in CAMPOS_SALIDA:
                    if k not in fila:
                        fila[k] = np.nan
                for region in REGIONES:
                    fila[f"{region}_n_pixeles_poligono"] = 0
                    fila[f"{region}_n_pixeles_validos"] = 0

            writer.writerow(fila)
            fout.flush()

            elapsed = time.time() - t0
            ritmo = elapsed / (i + 1)
            restante = ritmo * (len(pendientes) - i - 1)
            if (i + 1) % 10 == 0 or (i + 1) == len(pendientes):
                def fnum(v):
                    return f"{v:.1f}" if v == v else "NA"
                print(f"[{i+1}/{len(pendientes)}] {satelite} {fecha} frames={fila['n_frames']} "
                      f"embalse_val={fila.get('embalse_n_pixeles_validos','-')} "
                      f"chl_med={fnum(fila.get('embalse_chl_nn_mediana', float('nan')))} "
                      f"cortina_val={fila.get('cortina_n_pixeles_validos','-')} "
                      f"chl_cortina={fnum(fila.get('cortina_chl_nn_mediana', float('nan')))} "
                      f"| rate={ritmo:.1f}s/date, remaining~{restante/60:.0f} min")

    shutil.rmtree(TMP_DIR, ignore_errors=True)
    print("Done.")


if __name__ == "__main__":
    main()
